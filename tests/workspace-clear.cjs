const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {WorkspaceStore}=require('../integrations/chatbox/workspace-main.cjs');
const root=path.resolve(__dirname,'..'),folder=fs.mkdtempSync(path.join(root,'.temp/clear-'));
let store=new WorkspaceStore(path.join(folder,'store'),path.join(root,'dist'));
const a=path.join(folder,'original.txt'),b=path.join(folder,'added.txt');
fs.writeFileSync(a,'original source');fs.writeFileSync(b,'new source');
(async()=>{
  store.add('one',[a]);store.collection('one','create',{name:'资料'});
  const before=store.get('one');store.move('one',[before.sources[0].id+':'],'virtual:'+before.collections[0].id);
  const other=store.get('other');
  const paper=await store.worker('analyze',{workspace_id:before.id,columns:['Value'],rows:[[2],[3]],metrics:[{column:'Value',op:'sum'}]});
  const paperPath=store.resultPath('one',paper.file_id),paperBytes=fs.readFileSync(paperPath);
  store.clear('one');let cleared=store.get('one');assert.notEqual(cleared.id,before.id);
  assert.equal((await store.summary('one')).entries.length,0);
  assert.equal((await store.summary('one')).canUndoClear,true);
  await assert.rejects(store.worker('read',{workspace_id:before.id,file_id:before.sources[0].id+':'}),/清空/);
  assert(fs.readFileSync(paperPath).equals(paperBytes));assert.equal(store.get('other').id,other.id);
  store.clear('one');assert.equal(store.get('one').undoWorkspaceId,before.id,'Empty clear preserves undo');
  store=new WorkspaceStore(store.folder,store.root);store.add('one',[b]);
  const newPaper=await store.worker('analyze',{workspace_id:cleared.id,columns:['N'],rows:[[7]]});
  const newPaperPath=store.resultPath('one',newPaper.file_id);
  store.undoClear('one');let restored=store.get('one');
  assert.equal(restored.id,before.id);assert.equal(restored.collections.length,1);
  assert(restored.sources.some(s=>s.path===a&&s.parent===before.collections[0].id));
  assert(restored.sources.some(s=>s.path===b));assert(restored.sources.some(s=>s.path===newPaperPath));
  assert.equal((await store.summary('one')).canUndoClear,false);
  assert.equal((await store.worker('read',{workspace_id:before.id,file_id:before.sources[0].id+':'})).units[0].text,'original source');
  await assert.rejects(store.worker('list',{workspace_id:cleared.id}),/清空/);
  assert.throws(()=>store.undoClear('one'),/没有可撤销/);
  store.add('new',[a]);const draft=store.get('new');store.clear('new');const empty=store.get('new');store.adopt('new','sent',empty.id);store.undoClear('sent');assert.equal(store.get('sent').id,draft.id);
  assert.equal(fs.readFileSync(a,'utf8'),'original source');assert.equal(fs.readFileSync(b,'utf8'),'new source');assert(fs.readFileSync(paperPath).equals(paperBytes));
  console.log('PASS clear/undo: references, virtual hierarchy, papers, revoked MCP IDs, restart, new additions, repeat clear, chat isolation and first-send adoption; all source bytes unchanged');
})().catch(e=>{console.error(e);process.exitCode=1});
